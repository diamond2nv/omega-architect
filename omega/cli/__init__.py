@app.command("run")
def run_cmd(
    research_goal: str = typer.Argument(
        ..., help="Research goal description, e.g. 'Formalize NV spin Hamiltonian'"
    ),
    time_hours: float = typer.Option(
        2.0, "--time", "-t", help="Max run time in hours (2, 4, 8, 12, etc.)"
    ),
    model: str = typer.Option("local/default", "--model", "-m", help="LLM model ID to use"),
    checkpoint: str = typer.Option(
        "", "--resume", "-r", help="Path to checkpoint file to resume from"
    ),
) -> None:
    """Run autonomous proof search for a research goal.

    Runs unattended for *--time* hours, proving theorems related to the
    research goal. Checkpoints are saved periodically — use ``--resume``
    to continue from a previous run.

    Example:
        omega run "Formalize NV center spin Hamiltonian" --time 4
        omega run "Prove Maxwell equations in Lean" --time 8 --model deepseek/deepseek-chat
        omega run "Continue previous session" --resume ~/.omega/checkpoints/checkpoint_20260606_120000.json
    """
    from omega.runner import OmegaRunner, TheoremSpec

    # Build theorem list from the research goal keywords
    # For now, we create a default theorem based on the goal name
    theorems = [
        TheoremSpec(
            header=f"theorem research_goal_{i} : True :=",
            description=research_goal,
            priority=1,
            domain="general",
        )
        for i in range(1)
    ]

    time_budget_s = time_hours * 3600.0
    typer.echo(f"🚀 Starting {time_hours}h autonomous proof search")
    typer.echo(f"   Goal: {research_goal}")
    typer.echo(f"   Model: {model}")
    typer.echo(f"   Budget: {time_budget_s:.0f}s wall clock")
    typer.echo("")

    runner = OmegaRunner(
        time_budget_s=time_budget_s,
        model_id=model,
    )

    report = runner.run(
        research_goal=research_goal,
        theorems=theorems,
        resume_checkpoint=checkpoint,
    )

    typer.echo(report.summary())
    typer.echo("")

    # Show allocator provenance
    provenance = runner._allocator.provenance_summary()
    typer.echo(provenance)

    # Show cost report
    cost = runner._allocator.cost_report()
    typer.echo("\n💰 Cost breakdown:")
    typer.echo(
        f"   Pro (blueprint):  ${cost['pro_spent']:.4f} / ${cost['pro_remaining'] + cost['pro_spent']:.2f} budget"
    )
    typer.echo(
        f"   Flash (append):   ${cost['flash_spent']:.4f} / ${cost['flash_remaining'] + cost['flash_spent']:.2f} budget"
    )
    typer.echo(f"   Total:            ${cost['total_usd']:.4f}")

    # Show dynamic tok/s if local model was used
    tok_s = runner._bt.dynamic_tok_s()
    if tok_s > 0:
        typer.echo(f"⚡ Dynamic tok/s: {tok_s:.1f}")


