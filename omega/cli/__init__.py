@app.command("init")
def init_cmd(
    force: bool = typer.Option(False, "--force", "-f", help="Overwrite existing file"),
    output: str = typer.Option(
        "omega.toml",
        "--output",
        "-o",
        help="Output path for the config template",
    ),
    skip_lean: bool = typer.Option(
        False,
        "--skip-lean",
        help="Skip Lean/Mathlib discovery (budget config only)",
    ),
) -> None:
    """Generate a commented omega.toml configuration template with lean discovery.

    Phase 1: Writes the budget/resource config template.
    Phase 2: Auto-discovers Lean/Mathlib toolchain and writes ``[lean]`` section.
    """
    from omega.resource.lean_config import discover_and_write_lean_config

    out_path = Path(output)
    if out_path.exists() and not force:
        typer.echo(f"❌ {out_path} already exists. Use --force to overwrite.")
        raise typer.Exit(1)

    # ── Phase 1: Budget template ──
    template = _config_template()
    out_path.write_text(template, encoding="utf-8")
    typer.echo(f"✅ Phase 1 — Generated budget template: {out_path}")

    # ── Phase 2: Lean/Mathlib discovery ──
    if skip_lean:
        typer.echo("⏭️  Phase 2 — Lean discovery skipped (--skip-lean)")
    else:
        typer.echo("")
        typer.echo("🔍 Phase 2 — Discovering Lean/Mathlib toolchain...")
        try:
            cfg = discover_and_write_lean_config(str(out_path))
            typer.echo(f"   → Lean version:        {cfg.version}")
            typer.echo(f"   → Project path:        {cfg.project_path}")
            typer.echo(f"   → Lean binary:         {cfg.lean_bin}")
            typer.echo(f"   → Lake binary:         {cfg.lake_bin}")
            typer.echo(f"   → Mathlib oleans:      {cfg.olean_count:,}")
            typer.echo(f"   → Mathlib size:        {cfg.mathlib_size_gb:.1f} GB")
            typer.echo(f"   → Compile channel:     {cfg.compile_channel}")
            if cfg.compile_fallback:
                typer.echo(f"   → Fallback channels:   {cfg.compile_fallback}")
            typer.echo(f"✅ Lean discovery written to {out_path}")
        except FileNotFoundError as exc:
            typer.echo(f"⚠️  {exc}")
            typer.echo("   Run again with an existing config file, or run without --output.")
        except Exception as exc:
            typer.echo(f"⚠️  Lean discovery failed: {exc}")
            typer.echo("   The [lean] section was not written.  "
                       "T2 compilation will use hardcoded fallbacks.")

    typer.echo("")
    typer.echo("Done.  Next steps:")
    typer.echo("  omega config show    # verify loaded config (budget + lean)")
    typer.echo('  omega prove "theorem t : True := trivial"  # test T2 compile')


@app.command("config")
def config_cmd(
    ctx: typer.Context,
    action: str = typer.Argument(
        "show",
        help="Action: show / set / path",
    ),
    key: str = typer.Option("", "--key", "-k", help="Dot-path key (e.g., budget.max_tokens)"),
    value: str = typer.Option("", "--value", "-v", help="Value to set"),
) -> None:
    """View or modify Omega configuration.

    Actions:

    **show** (default) — Display current config with source annotation.

    **set** — Save a key=value to the config file (requires --key and --value).

    **path** — Show config file discovery path.
    """
    cfg_path = ctx.obj.get("config_path", "")

    if action == "path":
        found = _find_config_file()
        if found:
            typer.echo(f"📄 Config file: {found}")
        else:
            typer.echo("📄 No config file found (using defaults)")
        typer.echo(f"   OMEGA_CONFIG env: {cfg_path or '(not set)'}")
        typer.echo(f"   CWD:              {Path.cwd()}")
        return

    if action == "set":
        if not key:
            typer.echo("❌ --key is required for 'set' action")
            raise typer.Exit(1)
        if not value:
            typer.echo("❌ --value is required for 'set' action")
            raise typer.Exit(1)

        # Find or create config file
        config_file = cfg_path or _find_config_file() or "omega.toml"
        cfg_path_obj = Path(config_file)

        if cfg_path_obj.is_file():
            current = cfg_path_obj.read_text(encoding="utf-8")
        else:
            current = _config_template()
            cfg_path_obj.parent.mkdir(parents=True, exist_ok=True)

        # Parse key into TOML section path
        parts = key.split(".")
        if len(parts) >= 2:
            section = ".".join(parts[:-1])
            k = parts[-1]
            # Try to find and uncomment the line
            import re

            # Match commented or uncommented key
            pattern = re.compile(r"^(#\s*)?(" + re.escape(k) + r")\s*=\s*.*$", re.MULTILINE)
            # Parse value as number if possible
            try:
                parsed_val = json.loads(value)
            except (json.JSONDecodeError, ValueError):
                parsed_val = value

            # Format value
            if isinstance(parsed_val, bool):
                val_str = "true" if parsed_val else "false"
            elif isinstance(parsed_val, (int, float)):
                val_str = str(parsed_val)
            elif isinstance(parsed_val, list):
                val_str = json.dumps(parsed_val)
            else:
                val_str = f'"{parsed_val}"'

            replacement = f"{k} = {val_str}"
            if pattern.search(current):
                updated = pattern.sub(replacement, current)
            else:
                # Append to the right section
                section_header = f"[{section}]"
                if section_header in current:
                    # Find section and add after it
                    updated = current.replace(section_header, f"{section_header}\n{replacement}")
                else:
                    updated = current + f"\n[{section}]\n{replacement}\n"

            cfg_path_obj.write_text(updated, encoding="utf-8")
            reset_config_cache()
            typer.echo(f"✅ Set {key} = {val_str} in {cfg_path_obj}")
        else:
            typer.echo(
                "❌ Key must have at least two dot-separated parts (e.g., budget.max_tokens)"
            )
            raise typer.Exit(1)
        return

    # Default: show
    reset_config_cache()
    cfg = load_config(config_path=cfg_path)

    typer.echo("=" * 60)
    typer.echo("Ω-Architect Configuration")
    typer.echo("=" * 60)
    if cfg._source_file:
        typer.echo(f"📄 Source: {cfg._source_file}")
    else:
        typer.echo("📄 Source: defaults (no config file)")
    typer.echo("")

    # Display as formatted key=value
    flat = _flatten_config(cfg)
    for key_path, val in sorted(flat.items()):
        typer.echo(f"  {key_path:45s} = {val!r}")

    # Show Lean config if available
    try:
        from omega.resource.lean_config import load_lean_config

        lean_cfg = load_lean_config()
        if lean_cfg.project_exists() or lean_cfg.binaries_ok():
            typer.echo("")
            typer.echo("─" * 60)
            typer.echo("Lean/Mathlib Toolchain")
            typer.echo("─" * 60)
            typer.echo(f"  Lean version:              {lean_cfg.version}")
            typer.echo(f"  Project path:              {lean_cfg.project_path}")
            typer.echo(f"  Lean binary:               {lean_cfg.lean_bin}")
            typer.echo(f"  Lake binary:               {lean_cfg.lake_bin}")
            typer.echo(f"  Mathlib oleans:            {lean_cfg.olean_count:,}")
            typer.echo(f"  Mathlib size:              {lean_cfg.mathlib_size_gb:.1f} GB")
            typer.echo(f"  Compile channel:           {lean_cfg.compile_channel}")
            typer.echo(f"  Source:                    {lean_cfg._source or '(defaults)'}")
            typer.echo(f"  Status:                    {lean_cfg.summary()}")
    except ImportError:
        pass

    typer.echo("")
    typer.echo("To change: edit omega.toml or use `omega config set --key ... --value ...`")


# ── Helpers ─────────────────────────────────────────────────────


def _flatten_config(cfg: BudgetConfig) -> dict[str, Any]:
    """Flatten a BudgetConfig into dot-path key=value pairs."""
    result: dict[str, Any] = {}

    # Budget dimensions
    b = {
        "budget.max_tokens": cfg.max_tokens,
        "budget.max_cost_usd": cfg.max_cost_usd,
        "budget.max_time_s": cfg.max_time_s,
        "budget.max_attempts": cfg.max_attempts,
        "budget.min_confidence": cfg.min_confidence,
        "budget.epochs.max_epochs": cfg.epochs.max_epochs,
        "budget.epochs.convergence_threshold": cfg.epochs.convergence_threshold,
        "budget.epochs.window": cfg.epochs.window,
    }

    # Research
    r = {
        "research.max_tokens": cfg.research_max_tokens,
        "research.max_time_s": cfg.research_max_time_s,
        "research.max_papers": cfg.max_papers,
        "research.max_github_results": cfg.max_github_results,
    }

    # Models
    m: dict[str, Any] = {"models.free": list(cfg.free_models)}
    for model_id, prices in cfg.model_prices.items():
        short = model_id.replace("/", ".")
        m[f"models.{short}.input_per_token"] = prices.get("input_per_token", 0)
        m[f"models.{short}.output_per_token"] = prices.get("output_per_token", 0)

    result.update(b)
    result.update(r)
    result.update(m)
    return result


